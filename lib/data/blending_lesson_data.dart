import 'cvc_lesson_data.dart';

class BlendingSound {
  const BlendingSound(this.letters, this.audio);
  final List<int> letters;
  final String audio;
}

class BlendingLessonWord extends CvcLessonWord {
  const BlendingLessonWord(super.word, super.emoji,
      {super.picture, super.encouragement, this.soundGroups});

  /// Null uses the existing one-letter sounds. Empty uses the supplied whole
  /// word recording because its phonemes are not available as isolated clips.
  final List<BlendingSound>? soundGroups;
  bool get wholeWordOnly => soundGroups != null && soundGroups!.isEmpty;
  List<BlendingSound> get sounds =>
      soundGroups ??
      [
        for (var i = 0; i < word.length; i++)
          BlendingSound([i], super.soundAudio(i)),
      ];
  BlendingSound placementSound(int index) => wholeWordOnly
      ? BlendingSound([index], super.soundAudio(index))
      : sounds.firstWhere((sound) => sound.letters.contains(index));
  @override
  String get wordAudio => 'blend-word-$slug';
  @override
  String get praiseAudio => 'blend-praise-$slug';
  @override
  String get praise =>
      '${encouragement ?? 'Great job'}! ${word.split('').join('-')} makes $slug!';
}

